import { readFile, writeFile } from 'node:fs/promises';

const LIBRARY = new URL('../src/mtp.js', import.meta.url);
const DEMO = new URL('../_site/script.js', import.meta.url);
const OUTPUT = new URL('../_site/demo.js', import.meta.url);
const IMPORT = "import Mtp, { OBJECT_FORMAT } from '../src/mtp.js';\n\n";

function stripExports(source) {
  return source.replace(/^export default /gm, '').replace(/^export /gm, '');
}

function stripImport(source) {
  if (!source.startsWith(IMPORT)) {
    throw new Error('_site/script.js must start with the library import.');
  }
  return source.slice(IMPORT.length);
}

function build(library, demo) {
  return (
    '// Generated by scripts/build-demo.js. Do not edit.\n' +
    '(() => {\n' +
    "  'use strict';\n\n" +
    `${stripExports(library)}\n` +
    `${stripImport(demo)}\n` +
    '})();\n'
  );
}

const library = await readFile(LIBRARY, 'utf8');
const demo = await readFile(DEMO, 'utf8');
const bundle = build(library, demo);

if (process.argv.includes('--check')) {
  const current = await readFile(OUTPUT, 'utf8').catch(() => '');

  if (current !== bundle) {
    console.error('_site/demo.js is out of date. Run `make demo-bundle`.');
    process.exitCode = 1;
  }
} else {
  await writeFile(OUTPUT, bundle);
}
